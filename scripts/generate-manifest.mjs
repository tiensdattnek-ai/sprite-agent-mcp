#!/usr/bin/env node
/**
 * Generate integrity/manifest.json (SHA-256 of every tracked source/config file).
 * Human operator only: `npm run integrity`. The MCP tool sprite_verify_integrity
 * reads this file; agents must never regenerate it to "hide" an edit.
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync, statSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const TRACKED_DIRS = ["src", "scripts", "tests", ".github", ".cursor", "docs"];
const TRACKED_FILES = [
  "package.json", "tsconfig.json", "vitest.config.ts", "README.md", "README.en.md",
  "AGENTS.md", "POLICY.md", "CONTRIBUTING.md", "CODE_OF_CONDUCT.md", "SECURITY.md",
  "CHANGELOG.md", "LICENSE", "mcp.json", "server.json", "smithery.yaml",
  "Dockerfile", ".gitignore", ".npmignore",
];

function walk(dir) {
  const out = [];
  if (!existsSync(dir)) return out;
  for (const entry of readdirSync(dir).sort()) {
    const abs = path.join(dir, entry);
    if (statSync(abs).isDirectory()) out.push(...walk(abs));
    else out.push(path.relative(ROOT, abs).replace(/\\/g, "/"));
  }
  return out;
}

const files = {};
const list = [...TRACKED_DIRS.flatMap(d => walk(path.join(ROOT, d))), ...TRACKED_FILES.filter(f => existsSync(path.join(ROOT, f)))].sort();
for (const rel of new Set(list)) {
  if (rel.startsWith("sprite-output") || rel.includes("node_modules") || rel.startsWith("dist/")) continue;
  files[rel] = createHash("sha256").update(readFileSync(path.join(ROOT, rel))).digest("hex");
}
mkdirSync(path.join(ROOT, "integrity"), { recursive: true });
const manifest = {
  format: "sprite-agent-mcp/integrity-manifest",
  version: 1,
  generatedAt: new Date().toISOString(),
  note: "Generated by a HUMAN with `npm run integrity`. Agents: read via sprite_verify_integrity, never edit/regenerate.",
  files,
};
writeFileSync(path.join(ROOT, "integrity", "manifest.json"), JSON.stringify(manifest, null, 2) + "\n");
console.log(`✅ integrity/manifest.json — ${Object.keys(files).length} files hashed`);
